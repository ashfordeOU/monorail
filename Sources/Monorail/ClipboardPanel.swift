    @ObservedObject private var clips = ClipboardWatch.shared

    var body: some View {
        LazyVGrid(columns: [GridItem(.flexible(), spacing: 8), GridItem(.flexible())], spacing: 8) {
            tool("doc.on.clipboard.fill", "Clipboard", clipsLine, Tone.blue, openClipboard)

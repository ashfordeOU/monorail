    }
}

/// A clip's small picture: the image itself, a colour swatch, or its kind's symbol.
struct ClipThumb: View {
    let clip: ClipHistory.Clip
    var size: CGFloat = 28

    var body: some View {
        Group {
            if clip.kind == .image, let url = ClipboardWatch.shared.imageURL(clip), let image = NSImage(contentsOf: url) {
                Image(nsImage: image).resizable().aspectRatio(contentMode: .fill)
            } else if clip.kind == .colour, clip.sensitive == nil, let colour = Self.colour(clip.text) {
                colour
            } else {
                Image(systemName: clip.sensitive != nil ? "eye.slash" : clip.kind.symbol)
                    .font(.system(size: size * 0.42, weight: .medium)).foregroundStyle(.secondary)
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
                    .background(Color.primary.opacity(0.06))
            }
        }
        .frame(width: size, height: size)
        .clipShape(RoundedRectangle(cornerRadius: size * 0.22, style: .continuous))
        .overlay(RoundedRectangle(cornerRadius: size * 0.22, style: .continuous).strokeBorder(Color.primary.opacity(0.1)))
        .accessibilityHidden(true)
    }

    static func colour(_ text: String) -> Color? {
        var hex = text.trimmingCharacters(in: .whitespaces)
        guard hex.hasPrefix("#") else { return nil }
        hex.removeFirst()
        if hex.count == 3 { hex = hex.map { "\($0)\($0)" }.joined() }
        guard hex.count >= 6, let value = UInt32(hex.prefix(6), radix: 16) else { return nil }
        return Color(red: Double((value >> 16) & 0xFF) / 255, green: Double((value >> 8) & 0xFF) / 255, blue: Double(value & 0xFF) / 255)
    }
}

/// The Clipboard page in the panel: search, kinds, pinned first, ⌘⌃ numbers for the last ten, and the full window.

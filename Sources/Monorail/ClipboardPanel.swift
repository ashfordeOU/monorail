                                .overlay(RoundedRectangle(cornerRadius: 5).strokeBorder(Color.primary.opacity(0.15)))
                            ForEach([colour.hex, colour.rgb, colour.hsl], id: \.self) { value in
                                Button(value) { clips.copy(value) }.buttonStyle(.plain).font(.system(size: 10.5, design: .monospaced)).lineLimit(1)
                                    .help("Copy \(value)")
                            }
                        }
                    }
                }
                .tile()
            }
        }
        .padding(12)
    }

    private var kindChips: some View {
        let counts = clips.history.kindCounts
        let kinds = ClipKind.allCases.filter { (counts[$0] ?? 0) > 0 }
        return ScrollView(.horizontal, showsIndicators: false) {
            HStack(spacing: 5) {
                chip("All", nil)
                ForEach(kinds, id: \.self) { chip($0.title, $0) }
            }
        }
    }

    private func chip(_ title: String, _ value: ClipKind?) -> some View {
        Button { kind = value } label: {
            Text(title).font(.system(size: 11, weight: kind == value ? .semibold : .regular))
                .padding(.horizontal, 9).padding(.vertical, 3)
                .background(Capsule().fill(kind == value ? Color.accentColor.opacity(0.22) : Color.primary.opacity(0.06)))
        }
        .buttonStyle(.plain)
        .accessibilityAddTraits(kind == value ? .isSelected : [])
    }

    private func row(_ clip: ClipHistory.Clip, number: Int?) -> some View {
        HStack(spacing: 8) {
            Button {
                if clip.sensitive != nil { clips.reveal(clip) } else { clips.use(clip, plain: NSEvent.modifierFlags.contains(.option)) }
            } label: {
                HStack(spacing: 8) {
                    ClipThumb(clip: clip)
                    VStack(alignment: .leading, spacing: 1) {
                        Text(clip.preview(64)).font(.system(size: 12)).lineLimit(1)
                        Text(details(clip)).font(.system(size: 10.5)).foregroundStyle(.tertiary).lineLimit(1)
                    }
                    Spacer(minLength: 0)
                }
                .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            .help(clip.sensitive != nil ? "Hidden because it looks like a secret. Click to show it." : "")
            if let number { Text("⌘⌃\(number % 10)").font(.system(size: 9.5, design: .rounded)).foregroundStyle(.tertiary) }
            Button { clips.togglePin(clip) } label: {
                Image(systemName: clip.pinned ? "pin.fill" : "pin").font(.system(size: 11)).foregroundStyle(clip.pinned ? Tone.ok : Color.secondary)
            }
            .buttonStyle(.plain)
            .accessibilityLabel(clip.pinned ? "Unpin" : "Pin")
        }
        .padding(.horizontal, 10).padding(.vertical, 5)
        .contextMenu { ClipMenu(clip: clip) }
    }

    private func details(_ clip: ClipHistory.Clip) -> String {
        var parts: [String] = []
        if !clip.boards.isEmpty { parts.append(clip.boards.joined(separator: ", ")) }
        if let app = clip.app { parts.append(app) }
        parts.append(clip.copied.formatted(.relative(presentation: .named)))
        if clip.remindAt != nil { parts.append("⏰") }
        return parts.joined(separator: " · ")
    }
}

/// The right-click menu for a clip, in the panel and the window.
struct ClipMenu: View {
    let clip: ClipHistory.Clip
    @ObservedObject private var clips = ClipboardWatch.shared

    var body: some View {
        Button(Edition.isAppStore ? "Copy" : "Paste") { clips.use(clip) }
        if clip.kind != .image && clip.files == nil { Button("Paste as Plain Text") { clips.use(clip, plain: true) } }
        if clip.sensitive != nil { Button("Show") { clips.reveal(clip) } }
        Button(clip.pinned ? "Unpin" : "Pin") { clips.togglePin(clip) }
        Menu("Add to Board") {
            ForEach(clips.history.boards, id: \.self) { board in Button(board) { clips.addToBoard([clip], board) } }
            if !clips.history.boards.isEmpty { Divider() }
            Button("New Board…") { if let name = ClipPrompt.ask("New board", "Name") { clips.addToBoard([clip], name) } }
        }
        Button("Tags…") {
            if let tags = ClipPrompt.ask("Tags", "Separate with commas", initial: clip.tags.joined(separator: ", ")) {
                clips.setTags(clip, tags.split(separator: ",").map(String.init))
            }
        }
        Menu("Remind Me") {
            Button("In an Hour") { clips.remind(clip, at: Date().addingTimeInterval(3600)) }
            Button("This Evening") { clips.remind(clip, at: Calendar.current.date(bySettingHour: 18, minute: 0, second: 0, of: Date()).map { $0 < Date() ? $0.addingTimeInterval(86400) : $0 }) }
            Button("Tomorrow Morning") { clips.remind(clip, at: Calendar.current.date(bySettingHour: 9, minute: 0, second: 0, of: Date().addingTimeInterval(86400))) }
            Button("Next Week") { clips.remind(clip, at: Date().addingTimeInterval(7 * 86400)) }
            if clip.remindAt != nil { Divider(); Button("No Reminder") { clips.remind(clip, at: nil) } }
        }
        if clip.kind == .image {
            if BackgroundRemover.available { Button("Remove Background") { clips.removeBackground(clip) } }
            if let text = clip.imageText, !text.isEmpty { Button("Copy Text in Image") { clips.copy(text) } }
        }
        Divider()
        Button("Delete") { clips.remove(clip) }
    }
}

/// A one-line question in a small alert.
enum ClipPrompt {
    static func ask(_ title: String, _ placeholder: String, initial: String = "") -> String? {
        let alert = NSAlert()
        alert.messageText = title
        let field = NSTextField(frame: NSRect(x: 0, y: 0, width: 260, height: 24))
        field.placeholderString = placeholder
        field.stringValue = initial
        alert.accessoryView = field
        alert.addButton(withTitle: "OK")
        alert.addButton(withTitle: "Cancel")
        alert.window.initialFirstResponder = field
        NSApp.activate(ignoringOtherApps: true)
        guard alert.runModal() == .alertFirstButtonReturn else { return nil }
        let value = field.stringValue.trimmingCharacters(in: .whitespacesAndNewlines)
        return value.isEmpty && initial.isEmpty ? nil : value
    }
}

/// The full Clipboard window: everything you copied as cards, sorted by kind, boards and tags,
/// with several at once for a moodboard or a board.
final class ClipboardWindow {
    static let shared = ClipboardWindow()
    private var window: NSWindow?

    func show() {
        NSApp.windows.filter { $0 is MenuBarPanel }.forEach { $0.orderOut(nil) }
        if let window {
            window.makeKeyAndOrderFront(nil)
            NSApp.activate(ignoringOtherApps: true)
            return
        }
        let window = NSWindow(contentRect: NSRect(x: 0, y: 0, width: 1000, height: 680),
                              styleMask: [.titled, .closable, .miniaturizable, .resizable, .fullSizeContentView], backing: .buffered, defer: false)
        window.title = "Clipboard"
        window.titlebarAppearsTransparent = true
        window.isReleasedWhenClosed = false
        window.minSize = NSSize(width: 760, height: 480)
        window.contentView = NSHostingView(rootView: ClipboardWindowRoot())
        window.center()
        window.setFrameAutosaveName("MonorailClipboard")
        self.window = window
        window.makeKeyAndOrderFront(nil)
        NSApp.activate(ignoringOtherApps: true)
    }
}

struct ClipboardWindowRoot: View {
    enum Filter: Hashable { case all, pinned, kind(ClipKind), board(String), tag(String), settings }

    @ObservedObject private var clips = ClipboardWatch.shared
    @State private var filter = Filter.all
    @State private var query = ""
    @State private var selected: Set<UUID> = []

    private var shown: [ClipHistory.Clip] {
        switch filter {
        case .all, .settings: return clips.history.shown(matching: query)
        case .pinned: return clips.history.shown(matching: query).filter(\.pinned)
        case .kind(let k): return clips.history.shown(matching: query, kind: k)
        case .board(let b): return clips.history.shown(matching: query, board: b)
        case .tag(let t): return clips.history.shown(matching: query, tag: t)
        }
    }

    var body: some View {
        HStack(spacing: 0) {
            sidebar.frame(width: 210).background(.regularMaterial)
            Divider()
            VStack(alignment: .leading, spacing: 12) {
                if filter == .settings, let store = DashboardContext.store {
                    ClipboardSettings(store: store)
                } else {
                    toolbar
                    if shown.isEmpty {
                        Text(query.isEmpty ? "Nothing here yet." : "Nothing matches.").foregroundStyle(.secondary).frame(maxWidth: .infinity, maxHeight: .infinity)
                    } else {
                        ScrollView {
                            LazyVGrid(columns: [GridItem(.adaptive(minimum: 190, maximum: 260), spacing: 12)], spacing: 12) {
                                ForEach(shown) { clip in card(clip) }
                            }
                            .padding(.bottom, 20)
                        }
                    }
                }
            }
            .padding(.horizontal, 20).padding(.top, 34)
            .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
            .background(Color(nsColor: .windowBackgroundColor))
        }
    }

    private var sidebar: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 2) {
                Text("Clipboard").font(.system(size: 20, weight: .bold)).padding(.leading, 8).padding(.top, 34).padding(.bottom, 8)
                item("All", "tray.full", .all, clips.history.clips.count)
                item("Pinned", "pin", .pinned, clips.history.clips.filter(\.pinned).count)
                section("KINDS")
                let counts = clips.history.kindCounts
                ForEach(ClipKind.allCases.filter { (counts[$0] ?? 0) > 0 }, id: \.self) { k in item(k.title, k.symbol, .kind(k), counts[k] ?? 0) }
                section("BOARDS")
                ForEach(clips.history.boards, id: \.self) { b in
                    item(b, "square.grid.2x2", .board(b), clips.history.clips.filter { $0.boards.contains(b) }.count)
                        .contextMenu {
                            Button("Rename…") { if let name = ClipPrompt.ask("Rename board", "Name", initial: b) { clips.renameBoard(b, name); filter = .board(name) } }
                            Button("Delete Board") { clips.deleteBoard(b); filter = .all }
                        }
                }
                Button { if let name = ClipPrompt.ask("New board", "Name") { clips.addToBoard(clips.history.clips.filter { selected.contains($0.id) }, name); filter = .board(name) } } label: {
                    Label(selected.isEmpty ? "New Board" : "New Board from Selection", systemImage: "plus").font(.system(size: 12)).padding(.horizontal, 8).padding(.vertical, 4)
                }
                .buttonStyle(.plain).foregroundStyle(.secondary)
                if !clips.history.allTags.isEmpty {
                    section("TAGS")
                    ForEach(clips.history.allTags.prefix(12), id: \.self) { t in item("#" + t, "tag", .tag(t), clips.history.clips.filter { $0.tags.contains(t) }.count) }
                }
                Divider().padding(.vertical, 8)
                item("Settings", "gearshape", .settings, nil)
            }
            .padding(.horizontal, 10)
        }
    }

    private func section(_ title: String) -> some View {
        Text(title).font(.system(size: 10.5, weight: .semibold)).foregroundStyle(.secondary).padding(.top, 12).padding(.leading, 8).padding(.bottom, 2)
    }

    private func item(_ title: String, _ symbol: String, _ value: Filter, _ count: Int?) -> some View {
        Button { filter = value; selected = [] } label: {
            HStack(spacing: 9) {
                Image(systemName: symbol).frame(width: 18)
                Text(title).lineLimit(1)
                Spacer()
                if let count { Text("\(count)").foregroundStyle(.secondary).monospacedDigit() }
            }
            .font(.system(size: 13, weight: filter == value ? .semibold : .regular))
            .padding(.horizontal, 8).padding(.vertical, 5)
            .background(RoundedRectangle(cornerRadius: 6, style: .continuous).fill(filter == value ? Color.accentColor.opacity(0.18) : .clear))
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .accessibilityAddTraits(filter == value ? .isSelected : [])
    }

    private var toolbar: some View {
        let chosen = clips.history.clips.filter { selected.contains($0.id) }
        let images = chosen.filter { $0.kind == .image }
        return HStack(spacing: 8) {
            TextField("Search everything you copied, including text in images", text: $query).textFieldStyle(.roundedBorder)
            if !chosen.isEmpty {
                Text("\(chosen.count) selected").foregroundStyle(.secondary).font(.system(size: 12))
                if images.count >= 2 { Button("Copy as Moodboard") { clips.copyMoodboard(images) } }
                Menu("Add to Board") {
                    ForEach(clips.history.boards, id: \.self) { b in Button(b) { clips.addToBoard(chosen, b) } }
                    Button("New Board…") { if let name = ClipPrompt.ask("New board", "Name") { clips.addToBoard(chosen, name) } }
                }
                .fixedSize()
                Button("Deselect") { selected = [] }
            }
        }
    }

    private func card(_ clip: ClipHistory.Clip) -> some View {
        let isSelected = selected.contains(clip.id)
        return VStack(alignment: .leading, spacing: 6) {
            ZStack(alignment: .topTrailing) {
                content(clip).frame(height: 120).frame(maxWidth: .infinity).clipped()
                if clip.pinned { Image(systemName: "pin.fill").font(.system(size: 10)).foregroundStyle(Tone.ok).padding(6) }
            }
            .background(Color.primary.opacity(0.04))
            .clipShape(RoundedRectangle(cornerRadius: 8, style: .continuous))
            HStack(spacing: 5) {
                Image(systemName: clip.kind.symbol).font(.system(size: 10)).foregroundStyle(.secondary)
                Text([clip.app, clip.copied.formatted(.relative(presentation: .named))].compactMap { $0 }.joined(separator: " · "))
                    .font(.system(size: 10.5)).foregroundStyle(.secondary).lineLimit(1)
            }
            if !clip.tags.isEmpty || !clip.boards.isEmpty {
                Text((clip.boards + clip.tags.map { "#" + $0 }).joined(separator: "  ")).font(.system(size: 10.5)).foregroundStyle(.tertiary).lineLimit(1)
            }
        }
        .padding(8)
        .background(RoundedRectangle(cornerRadius: 12, style: .continuous).fill(Color(nsColor: .controlBackgroundColor)))
        .overlay(RoundedRectangle(cornerRadius: 12, style: .continuous).strokeBorder(isSelected ? Color.accentColor : Color.primary.opacity(0.08), lineWidth: isSelected ? 2 : 1))
        .contentShape(Rectangle())
        .onTapGesture {
            if NSEvent.modifierFlags.contains(.command) || NSEvent.modifierFlags.contains(.shift) || !selected.isEmpty {
                if isSelected { selected.remove(clip.id) } else { selected.insert(clip.id) }
            } else if clip.sensitive != nil {
                clips.reveal(clip)
            } else {
                clips.use(clip)
            }
        }
        .contextMenu { ClipMenu(clip: clip) }
        .help(Edition.isAppStore ? "Click to copy · ⌘-click to select" : "Click to paste · ⌘-click to select")
        .accessibilityElement(children: .combine)
        .accessibilityAddTraits(isSelected ? .isSelected : [])
    }

    @ViewBuilder private func content(_ clip: ClipHistory.Clip) -> some View {
        if clip.kind == .image, let image = clips.image(clip) {
            Image(nsImage: image).resizable().aspectRatio(contentMode: .fill)
        } else if clip.kind == .colour, clip.sensitive == nil, let colour = ClipThumb.colour(clip.text) {
            ZStack(alignment: .bottomLeading) {
                colour
                Text(clip.text).font(.system(size: 12, weight: .semibold, design: .monospaced)).padding(6)
                    .background(Capsule().fill(.thinMaterial)).padding(6)
            }
        } else if clip.sensitive != nil {
            VStack(spacing: 4) {
                Image(systemName: "eye.slash").font(.system(size: 20)).foregroundStyle(.secondary)
                Text(clip.sensitive ?? "").font(.system(size: 12, weight: .semibold))
                Text("Click to show").font(.system(size: 10.5)).foregroundStyle(.secondary)
            }
        } else if let files = clip.files {
            VStack(alignment: .leading, spacing: 4) {
                ForEach(files.prefix(4), id: \.self) { path in
                    HStack(spacing: 6) {
                        Image(nsImage: NSWorkspace.shared.icon(forFile: path)).resizable().frame(width: 20, height: 20)
                        Text((path as NSString).lastPathComponent).font(.system(size: 11.5)).lineLimit(1)
                    }
                }
            }
            .padding(10).frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
        } else {
            Text(String(clip.text.prefix(400)))
                .font(clip.kind == .code ? .system(size: 10.5, design: .monospaced) : .system(size: 12))
                .foregroundStyle(clip.kind == .link ? Color.accentColor : Color.primary)
                .padding(10).frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
        }
    }
}


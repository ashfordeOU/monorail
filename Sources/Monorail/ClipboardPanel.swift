/// Remembers what you copy: text, images and files. Concealed copies (from password managers),
/// transient ones and copies made in ignored apps are never kept; copies that look like secrets are
/// kept out of sight until you reveal them. History lives in this app's folder on this Mac and nowhere else.
final class ClipboardWatch: ObservableObject {
    static let shared = ClipboardWatch()

    @Published private(set) var history = ClipHistory()
    @Published private(set) var colours: [PickedColour] = []
    @Published var note: String = "" { didSet { saveNoteSoon() } }

    private var timer: Timer?
    private var ticks = 0
    private var lastCount = NSPasteboard.general.changeCount
    private var noteSave: DispatchWorkItem?
    private var settings = AppSettings()
    private static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private var historyURL: URL { SettingsStore.directory.appendingPathComponent("clips.json") }
    private var noteURL: URL { SettingsStore.directory.appendingPathComponent("note.txt") }
    static var imagesFolder: URL { SettingsStore.directory.appendingPathComponent("clip-images") }

    init() {
        if let data = try? Data(contentsOf: historyURL), let saved = try? JSONDecoder().decode(ClipHistory.self, from: data) { history = saved }
        note = (try? String(contentsOf: noteURL, encoding: .utf8)) ?? ""
    }

    func apply(_ settings: AppSettings) {
        self.settings = settings
        history.keep = settings.clipboardKeep
        let on = settings.clipboardHistory && !SuiteRole.shared.pauses(.clipboardWatch)
        if on, timer == nil {
            lastCount = NSPasteboard.general.changeCount
            timer = Timer.every(0.8) { [weak self] _ in self?.poll() }
        } else if !on, timer != nil {
            timer?.invalidate()
            timer = nil
        }
        QuickPasteKeys.shared.set(on && settings.clipboardQuickPaste)
        NotchOpener.shared.set(on && settings.clipboardNotch)
    }

    private func poll() {
        ticks += 1
        if ticks % 40 == 0 { remindersDue() }
        let board = NSPasteboard.general
        guard board.changeCount != lastCount else { return }
        lastCount = board.changeCount
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipped) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        if let id = front?.bundleIdentifier, settings.clipboardIgnoredApps.contains(id) { return }
        let app = front?.localizedName
        var dropped: [ClipHistory.Clip] = []
        let text = board.string(forType: .string)
        if settings.clipboardImages,
           let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            dropped = history.addFiles(urls.map(\.path), app: app)
        } else if settings.clipboardImages, text == nil || ClipKind.detect(text ?? "") == .link,
                  let data = board.data(forType: .png) ?? board.data(forType: .tiff) {
            addImage(data, app: app)
            return
        } else if let text {
            let secret = settings.clipboardHideSensitive ? SensitiveClip.detect(text) : nil
            dropped = history.add(text, app: app, sensitive: secret)
        } else {
            return
        }
        forget(dropped)
        save()
    }

    /// Saves a copied image as PNG (the same picture twice is kept once), then reads its text for search.
    private func addImage(_ data: Data, app: String?) {
        guard data.count <= 40_000_000, let rep = NSBitmapImageRep(data: data), let png = rep.representation(using: .png, properties: [:]) else { return }
        let digest = SHA256.hash(data: png).prefix(12).map { String(format: "%02x", $0) }.joined()
        let name = "\(digest).png"
        try? FileManager.default.createDirectory(at: Self.imagesFolder, withIntermediateDirectories: true)
        let url = Self.imagesFolder.appendingPathComponent(name)
        if !FileManager.default.fileExists(atPath: url.path) { try? png.write(to: url) }
        let dropped = history.addImage(file: name, digest: digest, width: rep.pixelsWide, height: rep.pixelsHigh, app: app)
        forget(dropped.filter { $0.image != name })
        save()
        guard let clip = history.clips.first, clip.imageText == nil, let cg = rep.cgImage else { return }
        let id = clip.id
        DispatchQueue.global(qos: .utility).async {
            let words = Self.readText(cg)
            DispatchQueue.main.async {
                self.history.setImageText(id, words)
                self.save()
            }
        }
    }

    static func readText(_ image: CGImage) -> String {
        let request = VNRecognizeTextRequest()
        request.recognitionLevel = .accurate
        request.usesLanguageCorrection = true
        try? VNImageRequestHandler(cgImage: image).perform([request])
        return (request.results ?? []).compactMap { $0.topCandidates(1).first?.string }.joined(separator: "\n")
    }

    /// Image files no clip uses any more.
    private func forget(_ clips: [ClipHistory.Clip]) {
        let inUse = Set(history.clips.compactMap(\.image))
        for clip in clips {
            if let image = clip.image, !inUse.contains(image) { try? FileManager.default.removeItem(at: Self.imagesFolder.appendingPathComponent(image)) }
        }
    }

    private func remindersDue() {
        let due = history.takeDueReminders()
        guard !due.isEmpty else { return }
        save()
        for clip in due { notify("Back on your clipboard list", clip.preview(90)) }
    }

    private func notify(_ title: String, _ body: String) {
        let content = UNMutableNotificationContent()
        content.title = title
        content.body = body
        let center = UNUserNotificationCenter.current()
        center.requestAuthorization(options: [.alert, .sound]) { granted, _ in
            guard granted else { return }
            center.add(UNNotificationRequest(identifier: UUID().uuidString, content: content, trigger: nil))
        }
    }

    private func save() {
        try? FileManager.default.createDirectory(at: SettingsStore.directory, withIntermediateDirectories: true)
        if let data = try? JSONEncoder().encode(history) { try? data.write(to: historyURL, options: .atomic) }
    }

    private func saveNoteSoon() {
        noteSave?.cancel()
        let text = note, url = noteURL
        let work = DispatchWorkItem {
            try? FileManager.default.createDirectory(at: SettingsStore.directory, withIntermediateDirectories: true)
            try? text.write(to: url, atomically: true, encoding: .utf8)
        }
        noteSave = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6, execute: work)
    }

    // MARK: Changes

    /// Sample clips for the screenshots CI draws; nothing is saved.
    func preview(_ sample: ClipHistory) { history = sample }

    func togglePin(_ clip: ClipHistory.Clip) { history.togglePin(clip.id); save() }
    func remove(_ clip: ClipHistory.Clip) { if let gone = history.remove(clip.id) { forget([gone]) }; save() }
    func clear() { forget(history.clear()); save() }
    func reveal(_ clip: ClipHistory.Clip) { history.reveal(clip.id); save() }
    func setTags(_ clip: ClipHistory.Clip, _ tags: [String]) { history.setTags(clip.id, tags); save() }
    func addToBoard(_ clips: [ClipHistory.Clip], _ board: String) { for clip in clips { history.addToBoard(clip.id, board: board) }; save() }
    func removeFromBoard(_ clip: ClipHistory.Clip, _ board: String) { history.removeFromBoard(clip.id, board: board); save() }
    func deleteBoard(_ board: String) { history.deleteBoard(board); save() }
    func renameBoard(_ old: String, _ new: String) { history.renameBoard(old, to: new); save() }
    func remind(_ clip: ClipHistory.Clip, at date: Date?) { history.remind(clip.id, at: date); save() }

    func imageURL(_ clip: ClipHistory.Clip) -> URL? { clip.image.map { Self.imagesFolder.appendingPathComponent($0) } }
    func image(_ clip: ClipHistory.Clip) -> NSImage? { imageURL(clip).flatMap { NSImage(contentsOf: $0) } }

    // MARK: Using a clip

    /// Puts a clip back on the clipboard. Monorail also pastes it into the app you were in; Signalbox
    /// can't type for you inside the App Store's sandbox, so it copies and you press ⌘V.
    func use(_ clip: ClipHistory.Clip, plain: Bool = false) {
        let board = NSPasteboard.general
        board.clearContents()
        if clip.kind == .image, let image = image(clip) {
            board.writeObjects([image])
        } else if let files = clip.files {
            board.writeObjects(files.map { URL(fileURLWithPath: $0) as NSURL })
        } else {
            board.setString(plain ? PlainText.clean(clip.text) : clip.text, forType: .string)
        }
        lastCount = board.changeCount
        pasteIntoFrontApp()
    }

    /// Text only (search results and older callers).
    func use(_ text: String, plain: Bool = false) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(plain ? PlainText.clean(text) : text, forType: .string)
        lastCount = board.changeCount
        pasteIntoFrontApp()
    }

    private func pasteIntoFrontApp() {
        guard !Edition.isAppStore, AXIsProcessTrusted() else { return }
        NSApp.windows.filter { $0 is MenuBarPanel }.forEach { $0.orderOut(nil) }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.2) { Self.pressCommandV() }
    }

    /// ⌘⌃1 to ⌘⌃0: the last ten things copied.
    func quickPaste(_ number: Int) {
        let quick = history.quick
        guard number >= 1, number <= quick.count else { NSSound.beep(); return }
        use(quick[number - 1])
    }

    /// Strips formatting from what's on the clipboard now.
    func makeClipboardPlain() {
        guard let text = NSPasteboard.general.string(forType: .string) else { return }
        use(text, plain: true)
    }

    private static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    /// Several image clips laid out as one picture, on the clipboard.
    func copyMoodboard(_ clips: [ClipHistory.Clip]) {
        let images = clips.compactMap { image($0) }
        guard images.count >= 2 else { return }
        let width = 2000.0
        let layout = Moodboard.layout(sizes: images.map { (Double($0.size.width), Double($0.size.height)) }, width: width, rowHeight: 520, gap: 20)
        let size = NSSize(width: width, height: layout.height)
        let board = NSImage(size: size)
        board.lockFocus()
        NSColor.white.setFill()
        NSRect(origin: .zero, size: size).fill()
        for (image, frame) in zip(images, layout.frames) {
            // Flipped: the layout counts from the top.
            let rect = NSRect(x: frame.x, y: size.height - frame.y - frame.height, width: frame.width, height: frame.height)
            NSGraphicsContext.saveGraphicsState()
            NSBezierPath(roundedRect: rect, xRadius: 10, yRadius: 10).addClip()
            image.draw(in: rect)
            NSGraphicsContext.restoreGraphicsState()
        }
        board.unlockFocus()
        let paste = NSPasteboard.general
        paste.clearContents()
        paste.writeObjects([board])
    }

    /// A copy of an image clip with its background removed (macOS 14 and later), added as a new clip.
    func removeBackground(_ clip: ClipHistory.Clip) {
        guard let image = image(clip), let cg = image.cgImage(forProposedRect: nil, context: nil, hints: nil) else { return }
        DispatchQueue.global(qos: .userInitiated).async {
            guard let cut = BackgroundRemover.remove(cg) else {
                DispatchQueue.main.async { NSSound.beep() }
                return
            }
            let rep = NSBitmapImageRep(cgImage: cut)
            guard let png = rep.representation(using: .png, properties: [:]) else { return }
            DispatchQueue.main.async {
                let board = NSPasteboard.general
                board.clearContents()
                board.setData(png, forType: .png)
                self.lastCount = board.changeCount
                self.addImage(png, app: clip.app)
            }
        }
    }

    /// The system's colour loupe; the colour lands on the clipboard as hex.
    func pickColour() {
        NSApp.windows.filter { $0 is MenuBarPanel }.forEach { $0.orderOut(nil) }
        NSColorSampler().show { [weak self] picked in
            guard let self, let colour = picked?.usingColorSpace(.sRGB) else { return }
            let found = PickedColour(red: colour.redComponent, green: colour.greenComponent, blue: colour.blueComponent)
            self.colours.removeAll { $0 == found }
            self.colours.insert(found, at: 0)
            if self.colours.count > 8 { self.colours.removeLast() }
            let board = NSPasteboard.general
            board.clearContents()
            board.setString(found.hex, forType: .string)
            self.lastCount = board.changeCount
        }
    }

    func copy(_ text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
        lastCount = board.changeCount
    }
}

/// Cuts the subject out of a picture with Vision (macOS 14 and later).
enum BackgroundRemover {
    static var available: Bool { if #available(macOS 14.0, *) { return true } else { return false } }

    static func remove(_ image: CGImage) -> CGImage? {
        guard #available(macOS 14.0, *) else { return nil }
        let request = VNGenerateForegroundInstanceMaskRequest()
        let handler = VNImageRequestHandler(cgImage: image)
        guard (try? handler.perform([request])) != nil, let result = request.results?.first,
              let buffer = try? result.generateMaskedImage(ofInstances: result.allInstances, from: handler, croppedToInstancesExtent: true) else { return nil }
        let ci = CIImage(cvPixelBuffer: buffer)
        return CIContext().createCGImage(ci, from: ci.extent)
    }
}

/// ⌘⌃1 to ⌘⌃0 paste the last ten clips: system-wide shortcuts, which need no permission (and work in Signalbox).
final class QuickPasteKeys {
    static let shared = QuickPasteKeys()
    private var refs: [EventHotKeyRef?] = []
    private var handler: EventHandlerRef?
    private static let codes: [UInt32] = [18, 19, 20, 21, 23, 22, 26, 28, 25, 29]

    func set(_ on: Bool) {
        if on == !refs.isEmpty { return }
        if on { register() } else { unregister() }
    }

    private func register() {
        if handler == nil {
            var spec = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            InstallEventHandler(GetApplicationEventTarget(), { _, event, _ in
                var id = EventHotKeyID()
                GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID), nil, MemoryLayout<EventHotKeyID>.size, nil, &id)
                guard id.signature == QuickPasteKeys.signature else { return OSStatus(eventNotHandledErr) }
                let number = Int(id.id)
                DispatchQueue.main.async { ClipboardWatch.shared.quickPaste(number) }
                return noErr
            }, 1, &spec, nil, &handler)
        }
        for (index, code) in Self.codes.enumerated() {
            var ref: EventHotKeyRef?
            let id = EventHotKeyID(signature: Self.signature, id: UInt32(index + 1))
            RegisterEventHotKey(code, UInt32(cmdKey | controlKey), id, GetApplicationEventTarget(), 0, &ref)
            refs.append(ref)
        }
    }

    private func unregister() {
        for ref in refs { if let ref { UnregisterEventHotKey(ref) } }
        refs = []
    }

    static let signature: OSType = 0x4D52_4350 // "MRCP"
}

/// Push the pointer up into the notch and hold for a moment: the clipboard opens under the menu bar.
final class NotchOpener {
    static let shared = NotchOpener()
    var open: () -> Void = {}
    private var monitor: Any?
    private var since: Date?

    func set(_ on: Bool) {
        if on, monitor == nil {
            monitor = NSEvent.addGlobalMonitorForEvents(matching: [.mouseMoved]) { [weak self] _ in self?.moved() }
        } else if !on, let m = monitor {
            NSEvent.removeMonitor(m)
            monitor = nil
        }
    }

    private func moved() {
        let point = NSEvent.mouseLocation
        guard let screen = NSScreen.screens.first(where: { $0.frame.contains(point) }), screen.safeAreaInsets.top > 0,
              let left = screen.auxiliaryTopLeftArea, let right = screen.auxiliaryTopRightArea else { since = nil; return }
        let inNotch = point.y >= screen.frame.maxY - 2 && point.x > left.maxX && point.x < right.minX
        guard inNotch else { since = nil; return }
        if since == nil { since = Date(); return }
        if let s = since, Date().timeIntervalSince(s) > 0.25 {
            since = .distantFuture
            open()
        }
    }
}

/// Tools on Home: Clipboard, a colour picker, text from a picture and a note.

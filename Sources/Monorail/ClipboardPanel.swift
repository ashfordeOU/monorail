/// Remembers what you copy. Concealed copies (from password managers) and transient ones are never kept.
/// History lives in Monorail's folder on this Mac and nowhere else.
final class ClipboardWatch: ObservableObject {
    static let shared = ClipboardWatch()

    @Published private(set) var history = ClipHistory()
    @Published private(set) var colours: [PickedColour] = []
    @Published var note: String = "" { didSet { saveNoteSoon() } }

    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var noteSave: DispatchWorkItem?
    private static let skipped: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private var historyURL: URL { SettingsStore.directory.appendingPathComponent("clips.json") }
    private var noteURL: URL { SettingsStore.directory.appendingPathComponent("note.txt") }

    init() {
        if let data = try? Data(contentsOf: historyURL), let saved = try? JSONDecoder().decode(ClipHistory.self, from: data) { history = saved }
        note = (try? String(contentsOf: noteURL, encoding: .utf8)) ?? ""
    }

    func apply(_ settings: AppSettings) {
        history.keep = settings.clipboardKeep
        if settings.clipboardHistory, !SuiteRole.shared.pauses(.clipboardWatch), timer == nil {
            lastCount = NSPasteboard.general.changeCount
            timer = Timer.every(0.8) { [weak self] _ in self?.poll() }
        } else if !settings.clipboardHistory || SuiteRole.shared.pauses(.clipboardWatch), timer != nil {
            timer?.invalidate()
            timer = nil
        }
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastCount else { return }
        lastCount = board.changeCount
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipped), let text = board.string(forType: .string) else { return }
        history.add(text, app: NSWorkspace.shared.frontmostApplication?.localizedName)
        save()
    }

    private func save() {
        try? FileManager.default.createDirectory(at: SettingsStore.directory, withIntermediateDirectories: true)
        if let data = try? JSONEncoder().encode(history) { try? data.write(to: historyURL, options: .atomic) }
    }

    private func saveNoteSoon() {
        noteSave?.cancel()
        let text = note, url = noteURL
        let work = DispatchWorkItem {
            try? FileManager.default.createDirectory(at: SettingsStore.directory, withIntermediateDirectories: true)
            try? text.write(to: url, atomically: true, encoding: .utf8)
        }
        noteSave = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6, execute: work)
    }

    func togglePin(_ clip: ClipHistory.Clip) { history.togglePin(clip.id); save() }
    func remove(_ clip: ClipHistory.Clip) { history.remove(clip.id); save() }
    func clear() { history.clear(); save() }

    /// Copies text back. Monorail also pastes it into the app you were in; Station can't type for
    /// you inside the App Store's sandbox, so it copies and you press ⌘V.
    func use(_ text: String, plain: Bool = false) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(plain ? PlainText.clean(text) : text, forType: .string)
        lastCount = board.changeCount
        guard !Edition.isAppStore, AXIsProcessTrusted() else { return }
        NSApp.windows.filter { $0 is MenuBarPanel }.forEach { $0.orderOut(nil) }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.2) { Self.pressCommandV() }
    }

    /// Strips formatting from what's on the clipboard now.
    func makeClipboardPlain() {
        guard let text = NSPasteboard.general.string(forType: .string) else { return }
        use(text, plain: true)
    }

    private static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            let event = CGEvent(keyboardEventSource: source, virtualKey: 9, keyDown: down)
            event?.flags = .maskCommand
            event?.post(tap: .cghidEventTap)
        }
    }

    /// The system's colour loupe; the colour lands on the clipboard as hex.
    func pickColour() {
        NSApp.windows.filter { $0 is MenuBarPanel }.forEach { $0.orderOut(nil) }
        NSColorSampler().show { [weak self] picked in
            guard let self, let colour = picked?.usingColorSpace(.sRGB) else { return }
            let found = PickedColour(red: colour.redComponent, green: colour.greenComponent, blue: colour.blueComponent)
            self.colours.removeAll { $0 == found }
            self.colours.insert(found, at: 0)
            if self.colours.count > 8 { self.colours.removeLast() }
            let board = NSPasteboard.general
            board.clearContents()
            board.setString(found.hex, forType: .string)
            self.lastCount = board.changeCount
        }
    }

    func copy(_ text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
        lastCount = board.changeCount
    }
}

/// Tools on Home: Clipboard, a colour picker, text from a picture and a note.
struct ToolsRow: View {
    let openClipboard: () -> Void
    let openNote: () -> Void
    let openText: () -> Void
    @ObservedObject private var clips = ClipboardWatch.shared

    var body: some View {
        LazyVGrid(columns: [GridItem(.flexible(), spacing: 8), GridItem(.flexible())], spacing: 8) {
            tool("doc.on.clipboard.fill", "Clipboard", clips.history.clips.first?.preview(24) ?? "Empty", Tone.blue, openClipboard)
            tool("eyedropper", "Colour", clips.colours.first?.hex ?? "Pick from screen", Color(nsColor: .systemPink)) { clips.pickColour() }
            tool("text.viewfinder", "Text", "From a picture", Color(nsColor: .systemTeal), openText)
            tool("note.text", "Notes", clips.note.isEmpty ? (AppleNotes.available ? "Quick note and Apple Notes" : "Jot something") : "\(PlainText.counts(clips.note).words) words", Tone.ok, openNote)
        }
    }

    private func tool(_ symbol: String, _ title: String, _ detail: String, _ tint: Color, _ action: @escaping () -> Void) -> some View {
        Button(action: action) {
            VStack(alignment: .leading, spacing: 6) {
                Image(systemName: symbol).font(.system(size: 12, weight: .semibold)).foregroundStyle(.white)
                    .frame(width: 26, height: 26).background(Circle().fill(tint))
                Text(title).font(.system(size: 12, weight: .semibold))
                Text(detail).font(.system(size: 10.5)).foregroundStyle(.secondary).lineLimit(1)
            }
            .frame(maxWidth: .infinity, alignment: .leading)
            .tile()
        }
        .buttonStyle(PressStyle())
        .accessibilityLabel(Text("\(title): \(detail)"))
    }
}

/// The Clipboard page: search, pinned clips first, click to paste, and the colours you picked.
struct ClipboardPage: View {
    let onBack: () -> Void
    @ObservedObject var store: SettingsStore
    @ObservedObject private var clips = ClipboardWatch.shared
    @State private var query = ""

    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            PageHeader(back: Brand.name, title: "Clipboard", onBack: onBack)
            if !store.settings.clipboardHistory {
                VStack(alignment: .leading, spacing: 6) {
                    Text("Clipboard history is off.").font(.system(size: 12, weight: .semibold))
                    Text("Turn it on to find anything you copied, pin what you reuse, and paste it as plain text. Passwords are never kept.")
                        .font(.system(size: 11.5)).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)
                    Button("Turn On") { store.settings.clipboardHistory = true }.controlSize(.small)
                }
                .tile()
            } else {
                TextField("Search clipboard", text: $query).textFieldStyle(.roundedBorder).font(.system(size: 12))
                let shown = clips.history.shown(matching: query).prefix(12)
                VStack(spacing: 0) {
                    if shown.isEmpty {
                        Text(query.isEmpty ? "Copy something and it shows up here." : "Nothing matches.")
                            .font(.system(size: 12)).foregroundStyle(.secondary).frame(maxWidth: .infinity, alignment: .leading).padding(10)
                    }
                    ForEach(Array(shown)) { clip in row(clip) }
                }
                .background(RoundedRectangle(cornerRadius: 10, style: .continuous).fill(Color.primary.opacity(0.05)))
                HStack {
                    Text(Edition.isAppStore ? "Click to copy, then ⌘V" : "Click to paste · ⌥-click for plain text")
                        .font(.system(size: 11)).foregroundStyle(.tertiary)
                    Spacer()
                    Button("Clear") { clips.clear() }.buttonStyle(.link).font(.system(size: 11))
                }
            }
            if !clips.colours.isEmpty {
                VStack(alignment: .leading, spacing: 6) {
                    Text("COLOURS").font(.label).foregroundStyle(.secondary)
                    ForEach(clips.colours, id: \.hex) { colour in
                        HStack(spacing: 8) {
                            RoundedRectangle(cornerRadius: 5).fill(Color(red: colour.red, green: colour.green, blue: colour.blue)).frame(width: 22, height: 22)
                                .overlay(RoundedRectangle(cornerRadius: 5).strokeBorder(Color.primary.opacity(0.15)))
                            ForEach([colour.hex, colour.rgb, colour.hsl], id: \.self) { value in
                                Button(value) { clips.copy(value) }.buttonStyle(.plain).font(.system(size: 10.5, design: .monospaced)).lineLimit(1)
                                    .help("Copy \(value)")
                            }
                        }
                    }
                }
                .tile()
            }
        }
        .padding(12)
    }

    private func row(_ clip: ClipHistory.Clip) -> some View {
        HStack(spacing: 8) {
            Button {
                clips.use(clip.text, plain: NSEvent.modifierFlags.contains(.option))
            } label: {
                VStack(alignment: .leading, spacing: 1) {
                    Text(clip.preview(70)).font(.system(size: 12)).lineLimit(1)
                    Text([clip.app, clip.copied.formatted(.relative(presentation: .named))].compactMap { $0 }.joined(separator: " · "))
                        .font(.system(size: 10.5)).foregroundStyle(.tertiary)
                }
                .frame(maxWidth: .infinity, alignment: .leading)
                .contentShape(Rectangle())
            }
            .buttonStyle(.plain)
            Button { clips.togglePin(clip) } label: {
                Image(systemName: clip.pinned ? "pin.fill" : "pin").font(.system(size: 11)).foregroundStyle(clip.pinned ? Tone.ok : Color.secondary)
                    .accessibilityLabel(clip.pinned ? "Unpin" : "Pin")
            }
            .buttonStyle(.plain)
        }
        .padding(.horizontal, 10).padding(.vertical, 6)
        .contextMenu {
            Button("Paste as Plain Text") { clips.use(clip.text, plain: true) }
            Button(clip.pinned ? "Unpin" : "Pin") { clips.togglePin(clip) }
            Button("Delete") { clips.remove(clip) }
        }
    }
}

/// A quick note that saves as you type.
struct NotePage: View {
    let onBack: () -> Void
    @ObservedObject private var clips = ClipboardWatch.shared

    var body: some View {
        let counts = PlainText.counts(clips.note)
        VStack(alignment: .leading, spacing: 8) {
            PageHeader(back: Brand.name, title: "Note", onBack: onBack)
            TextEditor(text: $clips.note)
                .font(.system(size: 13))
                .scrollContentBackground(.hidden)
                .padding(6)
                .frame(height: 220)
                .background(RoundedRectangle(cornerRadius: 10, style: .continuous).fill(Color.primary.opacity(0.05)))
            HStack {
                Text("\(counts.words) words · \(counts.characters) characters").font(.system(size: 11)).foregroundStyle(.tertiary)
                Spacer()
                Button("Copy") { clips.copy(clips.note) }.controlSize(.small).disabled(clips.note.isEmpty)
            }
        }
        .padding(12)
    }
}

                VStack(alignment: .leading, spacing: 6) {
                    Text("Clipboard history is off.").font(.system(size: 12, weight: .semibold))
                    Text("Turn it on to find anything you copied (text, images and files), pin what you reuse and paste it as plain text. Passwords are never kept, and keys and card numbers stay hidden.")
                        .font(.system(size: 11.5)).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)
                    Button("Turn On") { store.settings.clipboardHistory = true }.controlSize(.small)
                }
                .tile()
            } else {
                HStack(spacing: 6) {
                    TextField("Search, including text in images", text: $query).textFieldStyle(.roundedBorder).font(.system(size: 12))
                    Button { ClipboardWindow.shared.show() } label: { Image(systemName: "macwindow") }
                        .buttonStyle(.borderless).help("Open the Clipboard window").accessibilityLabel("Open the Clipboard window")
                }
                kindChips
                let shown = clips.history.shown(matching: query, kind: kind).prefix(12)
                let quick = clips.history.quick.map(\.id)
                VStack(spacing: 0) {
                    if shown.isEmpty {
                        Text(query.isEmpty && kind == nil ? "Copy something and it shows up here." : "Nothing matches.")
                            .font(.system(size: 12)).foregroundStyle(.secondary).frame(maxWidth: .infinity, alignment: .leading).padding(10)
                    }
                    ForEach(Array(shown)) { clip in row(clip, number: quick.firstIndex(of: clip.id).map { $0 + 1 }) }
                }
                .background(RoundedRectangle(cornerRadius: 10, style: .continuous).fill(Color.primary.opacity(0.05)))
                HStack {
                    Text(Edition.isAppStore ? "Click to copy, then ⌘V · ⌘⌃1–0 copy the last ten" : "Click to paste · ⌥-click plain · ⌘⌃1–0 the last ten")
                        .font(.system(size: 11)).foregroundStyle(.tertiary)
                    Spacer()
                    Button("Clear") { clips.clear() }.buttonStyle(.link).font(.system(size: 11))
                }
            }
            if !clips.colours.isEmpty {
                VStack(alignment: .leading, spacing: 6) {
                    Text("COLOURS").font(.label).foregroundStyle(.secondary)

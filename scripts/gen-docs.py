#!/usr/bin/env python3
"""Writes docs/ACTIONS.md (every action) and docs/SETTINGS.md (every setting) from the source,
so the reference can never fall behind. `--check` fails if the files are out of date (CI runs this)."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def actions():
    src = read("Sources/MonorailCore/Action.swift")
    enum = src[src.index("public enum Action"):]
    cases = []
    for name, raw in re.findall(r"^    case (\w+)(?: = \"([^\"]+)\")?\s*$", enum, re.M):
        cases.append((name, raw or name))
    titles = dict(re.findall(r'case \.(\w+): return "([^"]+)"', enum))
    unbound = set(re.findall(r"\.(\w+)", enum[enum.index("unboundByDefault"):enum.index("]", enum.index("unboundByDefault"))]))
    lines = ["# Every Monorail action", "",
             "Generated from `Sources/MonorailCore/Action.swift` by `scripts/gen-docs.py`. Don't edit by hand.", "",
             "Run any action from the command palette (⌃⌥/), with `open -g monorail://<name>`, `monorail <name>`,",
             "the local API (`POST /action`), MCP (`perform_action`), AppleScript or a script (`monorail.perform`).",
             "Give any of them a key in **Settings → Shortcuts**.", "",
             f"{len(cases)} actions.", "",
             "| Action | Name | Default key |", "| --- | --- | --- |"]
    for name, raw in cases:
        title = titles.get(name, name)
        key = "none (add one in Settings)" if name in unbound else "yes (see Settings → Shortcuts)"
        lines.append(f"| {title} | `{raw}` | {key} |")
    return "\n".join(lines) + "\n"


def settings():
    src = read("Sources/MonorailCore/AppSettings.swift")
    body = src[src.index("public struct AppSettings"):]
    body = body[:body.index("enum CodingKeys")]
    rows, doc = [], []
    for line in body.splitlines():
        line = line.strip()
        if line.startswith("///"):
            doc.append(line[3:].strip())
            continue
        m = re.match(r"public var (\w+)(?:: ([^=]+))?(?: = (.+))?$", line)
        if m and "{" not in line:
            name, kind, default = m.group(1), (m.group(2) or "").strip(), (m.group(3) or "").strip()
            text = " ".join(doc).replace("|", "\\|")
            shown = default.replace("|", "\\|")
            rows.append(f"| `{name}` | {text} | `{shown}` |" if default else f"| `{name}` | {text} | |")
        doc = []
    lines = ["# Every Monorail setting", "",
             "Generated from `Sources/MonorailCore/AppSettings.swift` by `scripts/gen-docs.py`. Don't edit by hand.", "",
             "Settings live in `~/Library/Application Support/Monorail/settings.json`. Every one can be changed in the",
             "Settings window; organisations can enforce any of them with a configuration profile (MDM) using these keys.", "",
             f"{len(rows)} settings.", "",
             "| Key | What it does | Default |", "| --- | --- | --- |"] + rows
    return "\n".join(lines) + "\n"


PANE_TABS = {
    "GeneralPane": "general", "LayoutPane": "layout", "InputPane": "input", "AppearancePane": "appearance",
    "ThemeGrid": "appearance", "AppsPane": "apps", "QuickLaunchSection": "apps", "TemplatesSection": "apps",
    "SmartPane": "smart", "DevicesPane": "devices", "StayAwakePane": "awake", "AutomationPane": "automation",
    "WorkspaceConfigSection": "automation", "APISection": "automation", "InsightsPane": "insights",
    "TimeSection": "insights", "ShortcutsPane": "shortcuts", "AboutPane": "about", "UsageSection": "about",
}


def settings_index():
    """Every labelled control in the Settings panes, for the search field in Settings."""
    entries = []
    for path in ["Sources/Monorail/SettingsView.swift", "Sources/Monorail/SmartSettings.swift", "Sources/Monorail/Insights.swift"]:
        src = read(path)
        current = None
        for line in src.splitlines():
            m = re.match(r"\s*(?:private |fileprivate )?struct (\w+)\s*:\s*View", line)
            if m:
                current = PANE_TABS.get(m.group(1))
                continue
            if not current:
                continue
            for label in re.findall(r'(?:Toggle|Picker|LabeledContent|Stepper|Section|Button|Menu|DisclosureGroup)\("((?:[^"\\]|\\.)+)"', line):
                if "\\(" in label or len(label) < 4:
                    continue
                entries.append((label.replace("\\", ""), current))
    seen, unique = set(), []
    for label, tab in entries:
        if (label, tab) not in seen:
            seen.add((label, tab))
            unique.append((label, tab))
    def esc(t):
        return t.replace("\\", "\\\\").replace('"', '\\"')
    rows = "\n".join(f'        ("{esc(label)}", "{tab}"),' for label, tab in unique)
    return f"""#if os(macOS)
// Generated by scripts/gen-docs.py from the Settings panes. Don't edit by hand.
import Foundation

/// Every labelled setting and the Settings tab it lives in, for searching Settings.
enum SettingsIndex {{
    static let entries: [(label: String, tab: String)] = [
{rows}
    ]

    /// Settings whose label contains every word typed.
    static func search(_ query: String) -> [(label: String, tab: String)] {{
        let words = query.lowercased().split(separator: " ").map(String.init)
        guard !words.isEmpty else {{ return [] }}
        return entries.filter {{ entry in words.allSatisfy {{ entry.label.lowercased().contains($0) }} }}
    }}
}}
#endif
"""


def main():
    outputs = {"docs/ACTIONS.md": actions(), "docs/SETTINGS.md": settings(),
               "Sources/Monorail/SettingsIndex.swift": settings_index()}
    stale = []
    for path, text in outputs.items():
        full = os.path.join(ROOT, path)
        current = open(full, encoding="utf-8").read() if os.path.exists(full) else None
        if "--check" in sys.argv:
            if current != text:
                stale.append(path)
        else:
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w", encoding="utf-8") as f:
                f.write(text)
            print("Wrote", path)
    if stale:
        print("Out of date (run python3 scripts/gen-docs.py):", ", ".join(stale))
        sys.exit(1)


main()
